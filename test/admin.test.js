import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createApp } from '../src/app.js';
import { createConfigStore } from '../src/config.js';
import { hashPassword } from '../src/admin/auth.js';
import { createState } from '../src/state.js';

test('login, sessão, CSRF, edição, prévia, expiração e logout', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'panel-'));
  const path = join(dir, 'config.json');
  const company = { instance: 'alfa', displayName: 'Alfa', enabled: true, welcomeText: 'Olá', closingText: '', prefilledText: 'Oi', agents: [1, 2, 3].map(n => ({ label: `Pessoa ${n}`, phoneE164: `551199999${n}000` })) };
  await writeFile(path, JSON.stringify({ schemaVersion: 1, defaultCooldownHours: 24, companies: [company] }));
  const config = createConfigStore(path, { info() {}, error() {} });
  await config.reload();
  let time = 0;
  const state = createState(join(dir, 'state.sqlite'));
  const app = createApp({ config, state, worker: { snapshot: () => ({}) }, admin: { enabled: true, username: 'admin', passwordHash: await hashPassword('a-long-test-password'), origin: 'https://panel.example', now: () => time } });
  const origin = 'https://panel.example';
  const login = () => app.inject({ method: 'POST', url: '/admin/api/login', headers: { origin }, payload: { username: 'admin', password: 'a-long-test-password' } });
  try {
    assert.equal((await app.inject('/admin/api/companies')).statusCode, 401);
    assert.equal((await app.inject({ method: 'POST', url: '/admin/api/login', payload: { username: 'admin', password: 'a-long-test-password' } })).statusCode, 403);
    const result = await login();
    assert.equal(result.statusCode, 200);
    assert.match(result.headers['set-cookie'], /HttpOnly/);
    assert.match(result.headers['set-cookie'], /Secure/);
    const cookie = result.headers['set-cookie'].split(';')[0];
    const csrf = result.json().csrf;
    const headers = { cookie, origin, 'x-csrf-token': csrf };
    const reset = '/admin/api/companies/alfa/cooldown/reset';
    const release = { contact: '5511988887777' };
    for (const instance of ['alfa', 'beta']) state.sent({ instance, message_id: 'sent', contact: release.contact }, Date.now());
    assert.equal((await app.inject({ method: 'POST', url: reset, headers: { origin }, payload: release })).statusCode, 401);
    assert.equal((await app.inject({ method: 'POST', url: reset, headers: { cookie, origin }, payload: release })).statusCode, 403);
    assert.equal((await app.inject({ method: 'POST', url: reset, headers: { ...headers, origin: 'https://other.example' }, payload: release })).statusCode, 403);
    assert.equal((await app.inject({ method: 'POST', url: reset, headers, payload: { contact: 'invalid' } })).statusCode, 422);
    assert.equal((await app.inject({ method: 'POST', url: reset.replace('alfa', 'missing'), headers, payload: release })).statusCode, 404);
    assert.equal((await app.inject({ method: 'POST', url: reset, headers, payload: release })).statusCode, 200);
    assert.equal(state.clearCooldown('alfa', release.contact), 0);
    assert.equal(state.clearCooldown('beta', release.contact), 1);
    assert.equal((await app.inject({ url: '/admin/api/session', headers })).json().csrf, csrf);
    assert.equal((await app.inject({ url: '/admin/api/companies', headers })).json().companies.length, 1);
    const current = await app.inject({ url: '/admin/api/companies/alfa', headers });
    assert.equal(current.json().fields.cooldownHours, 24);
    assert.equal(current.json().fields.messageFormat, 'text');
    assert.equal(current.json().fields.includePrefilledText, true);
    const payload = { ...current.json().fields, cooldownHours: 1, welcomeText: '<img src=x onerror=alert(1)>' };
    for (const cooldownHours of [0, 721, 1.5, '1', null]) assert.equal((await app.inject({ method: 'PUT', url: '/admin/api/companies/alfa', headers: { ...headers, 'if-match': current.headers.etag }, payload: { ...payload, cooldownHours } })).statusCode, 422);
    assert.equal((await app.inject({ method: 'PUT', url: '/admin/api/companies/alfa', headers: { cookie, origin }, payload })).statusCode, 403);
    assert.equal((await app.inject({ method: 'PUT', url: '/admin/api/companies/alfa', headers: { ...headers, origin: 'https://other.example' }, payload })).statusCode, 403);
    assert.equal((await app.inject({ method: 'PUT', url: '/admin/api/companies/alfa', headers: { ...headers, 'if-match': current.headers.etag }, payload: { ...payload, enabled: false } })).statusCode, 400);
    assert.equal((await app.inject({ url: '/admin/api/companies/missing', headers })).statusCode, 404);
    assert.equal((await app.inject({ method: 'POST', url: '/admin/api/companies/alfa/preview', headers, payload: { ...payload, agents: [] } })).statusCode, 422);
    assert.equal((await app.inject({ method: 'PUT', url: '/admin/api/companies/alfa', headers, payload })).statusCode, 428);
    const preview = await app.inject({ method: 'POST', url: '/admin/api/companies/alfa/preview', headers, payload });
    assert.equal(preview.statusCode, 200);
    assert.ok(preview.json().text.startsWith(payload.welcomeText));
    payload.messageFormat = 'buttons';
    const buttonPreview = await app.inject({ method: 'POST', url: '/admin/api/companies/alfa/preview', headers, payload });
    assert.equal(buttonPreview.json().format, 'buttons');
    assert.equal(buttonPreview.json().content.buttons.length, 3);
    assert.equal(buttonPreview.json().content.buttons[0].displayText, payload.agents[0].label);
    payload.messageFormat = 'list';
    payload.includePrefilledText = false;
    payload.prefilledText = '';
    const listPreview = await app.inject({ method: 'POST', url: '/admin/api/companies/alfa/preview', headers, payload });
    assert.equal(listPreview.json().format, 'list');
    assert.equal(listPreview.json().content.sections[0].rows.length, 3);
    assert.equal(listPreview.json().content.buttonText, 'Escolher atendente');
    assert.doesNotMatch(listPreview.json().text, /\?text=/);
    payload.messageFormat = 'vcard';
    const cardsPreview = await app.inject({ method: 'POST', url: '/admin/api/companies/alfa/preview', headers, payload });
    assert.equal(cardsPreview.json().format, 'vcard');
    assert.equal(cardsPreview.json().content.contact.length, 3);
    assert.doesNotMatch(cardsPreview.json().text, /wa.me/);
    payload.messageFormat = 'image';
    payload.imageUrl = '';
    const imagePreview = await app.inject({ method: 'POST', url: '/admin/api/companies/alfa/preview', headers, payload });
    assert.equal(imagePreview.json().content.imageUrl, '/admin/example-banner.jpg');
    assert.match(imagePreview.json().text, /wa.me/);
    const sampleImage = await app.inject('/admin/example-banner.jpg');
    assert.equal(sampleImage.statusCode, 200);
    assert.match(sampleImage.headers['content-type'], /image\/jpeg/);
    const updated = await app.inject({ method: 'PUT', url: '/admin/api/companies/alfa', headers: { ...headers, 'if-match': current.headers.etag }, payload });
    assert.equal(updated.statusCode, 200);
    const restarted = createConfigStore(path, { info() {}, error() {} });
    await restarted.reload();
    assert.equal(restarted.company('alfa').cooldownHours, 1);
    assert.equal(restarted.company('alfa').messageFormat, 'image');
    assert.equal(restarted.company('alfa').imageUrl, '');
    assert.equal(restarted.company('alfa').includePrefilledText, false);
    assert.equal(restarted.company('alfa').prefilledText, '');
    assert.notEqual(updated.headers.etag, current.headers.etag);
    assert.equal((await app.inject({ method: 'PUT', url: '/admin/api/companies/alfa', headers: { ...headers, 'if-match': current.headers.etag }, payload })).statusCode, 412);
    assert.equal((await app.inject({ method: 'POST', url: '/admin/api/logout', headers, payload: {} })).statusCode, 204);
    assert.equal((await app.inject({ url: '/admin/api/session', headers })).statusCode, 401);
    const again = await login();
    time = 8 * 3_600_000;
    assert.equal((await app.inject({ url: '/admin/api/session', headers: { cookie: again.headers['set-cookie'].split(';')[0] } })).statusCode, 401);
    time = 0;
    for (let n = 0; n < 5; n++) assert.equal((await app.inject({ method: 'POST', url: '/admin/api/login', headers: { origin }, payload: { username: 'admin', password: 'wrong' } })).statusCode, 401);
    assert.equal((await login()).statusCode, 429);
    const page = await app.inject('/admin/');
    assert.equal(page.statusCode, 200);
    assert.match(page.headers['content-security-policy'], /default-src 'self'/);
    assert.equal((await app.inject('/admin/app.js')).statusCode, 200);
    assert.equal((await app.inject('/admin/model.js')).statusCode, 200);
    assert.equal((await app.inject('/admin/style.css')).statusCode, 200);
  } finally { await app.close(); state.close(); await rm(dir, { recursive: true, force: true }); }
});

test('painel desabilitado não registra rotas; credenciais inválidas impedem habilitação', () => {
  const options = { config: {}, state: {}, worker: {} };
  const app = createApp(options);
  assert.equal(app.hasRoute({ method: 'GET', url: '/admin/' }), false);
  assert.throws(() => createApp({ ...options, admin: { enabled: true } }));
  return app.close();
});
